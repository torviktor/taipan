-- Миграция: одноразовые токены привязки аккаунта к мессенджеру.
--
-- ЗАЧЕМ. Сейчас привязка требует от родителя набрать «/link 79XXXXXXXXX»
-- вручную. На 22.08.2026 из 57 активных родителей привязан НИ ОДИН, а девять
-- человек дошли до бота и на этом остановились — то есть ручной ввод номера
-- и есть то место, где теряются люди. Тренер вот-вот позовёт всех 57, и
-- повторять этот результат нельзя.
--
-- Вместо ввода — персональная ссылка: https://max.ru/<бот>?start=lnk_ТОКЕН
-- и https://t.me/<бот>?start=lnk_ТОКЕН. Родитель нажимает, бот получает
-- параметр в bot_started (MAX) или как «/start lnk_ТОКЕН» (Telegram) и
-- привязывает аккаунт сам.
--
-- ПОЧЕМУ ТОКЕН, А НЕ НОМЕР В ССЫЛКЕ. Ссылку пересылают. Если бы в параметре
-- лежал телефон или user_id, то первый же, кому её переслали, привязал бы к
-- себе чужой аккаунт и стал получать чужие уведомления — про чужих детей,
-- взносы и аттестации. Поэтому:
--   * токен НЕУГАДЫВАЕМ — 128 бит случайности, не производная от чего-либо;
--   * токен ОДНОРАЗОВЫЙ — used_at гасит его при первом использовании;
--   * токен ЖИВЁТ ОГРАНИЧЕННО — expires_at, две недели по умолчанию.
-- Пересланная ссылка после первого перехода бесполезна, а неиспользованная
-- протухает сама.
--
-- ПРО ДОПУСТИМЫЕ СИМВОЛЫ. MAX принимает в параметре только A-Za-z0-9_- и
-- отбрасывает параметр целиком БЕЗ СООБЩЕНИЯ ОБ ОШИБКЕ, если встретит что-то
-- ещё. Поэтому токен генерируется через secrets.token_urlsafe, чей алфавит
-- ровно этим и ограничен, а длина всей строки (lnk_ + 22 символа = 26)
-- заведомо меньше предела в 128 символов.
--
-- НЕ ПРИМЕНЕНА. Прогонять вручную, см. команды в конце.

BEGIN;

CREATE TABLE IF NOT EXISTS link_tokens (
    id          SERIAL PRIMARY KEY,
    user_id     INTEGER     NOT NULL REFERENCES users(id) ON DELETE CASCADE,

    -- Сам токен без префикса. VARCHAR(64) с запасом: сейчас 22 символа,
    -- но менять длину генератора не должно требовать миграции.
    token       VARCHAR(64) NOT NULL UNIQUE,

    created_at  TIMESTAMP   NOT NULL DEFAULT now(),
    expires_at  TIMESTAMP   NOT NULL,

    -- Погашение. NULL — токен ещё жив.
    used_at          TIMESTAMP,
    used_platform    VARCHAR(20),
    used_external_id VARCHAR(50)
);

-- Главный запрос: «есть ли у этого родителя живой токен, или выпустить новый».
-- Частичный индекс — погашенные и просроченные в выборку не попадают никогда,
-- а их со временем станет большинство.
CREATE INDEX IF NOT EXISTS ix_link_tokens_alive
    ON link_tokens (user_id, expires_at)
    WHERE used_at IS NULL;

-- Поиск при переходе по ссылке идёт по токену; UNIQUE уже даёт индекс,
-- отдельный не нужен.

COMMIT;

