-- Миграция: учёт доставки уведомлений в Telegram (notifications).
--
-- Мотивация. До 17.08.2026 результат отправки в Telegram нигде не сохранялся:
-- send_telegram_to_user возвращала True безусловно, а вызывающий код её ответ
-- игнорировал. Когда выяснилось, что канал до api.telegram.org теряет около
-- половины запросов, оценить масштаб потерь оказалось нечем — ни в БД, ни в
-- логах (логи умирали вместе с контейнером при каждом деплое).
--
-- Семантика tg_status:
--   NULL         — уведомление не предназначено для Telegram, живёт только в
--                  кабинете (так создаёт строки, например, недельный дайджест);
--   'pending'    — поставлено в очередь, разбирает app.tasks.deliver_telegram;
--   'sent'       — Telegram принял (HTTP 200);
--   'failed'     — не доставлено после всех попыток, причина в tg_error;
--   'no_account' — у пользователя нет привязанного Telegram, отправлять некуда.
--
-- NULL по умолчанию выбран намеренно: иначе фоновая задача подхватила бы все
-- ранее созданные уведомления и разослала бы их задним числом.
--
-- create_all() при старте бэка добавит эти колонки только на пустых БД —
-- на проде ALTER нужно прогнать вручную, ДО выката кода: иначе SQLAlchemy
-- начнёт запрашивать несуществующие колонки и роуты уведомлений отдадут 500.

-- ─────────────────────────────────────────────────────────────────────────────
-- ШАГ 1. Колонки.
-- ─────────────────────────────────────────────────────────────────────────────
ALTER TABLE notifications ADD COLUMN IF NOT EXISTS tg_status VARCHAR(20);
ALTER TABLE notifications ADD COLUMN IF NOT EXISTS tg_error  TEXT;

-- ─────────────────────────────────────────────────────────────────────────────
-- ШАГ 2. Индекс: фоновая задача выбирает строки строго по tg_status='pending',
-- частичный индекс держит его маленьким независимо от объёма таблицы.
-- ─────────────────────────────────────────────────────────────────────────────
CREATE INDEX IF NOT EXISTS ix_notifications_tg_pending
    ON notifications (id) WHERE tg_status = 'pending';

