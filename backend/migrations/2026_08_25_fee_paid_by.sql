-- Миграция: кто отметил взнос оплаченным.
--
-- ЗАЧЕМ. Отметка оплаты появляется в боте — то есть действие, меняющее
-- денежные данные, можно совершить с телефона в два касания. У такого
-- действия обязан быть автор: «кто поставил галочку» — первый вопрос, когда
-- родитель говорит «я не платил», а в системе стоит оплачено.
--
-- До сих пор отметку ставили только через кабинет, и там автор тоже не
-- сохранялся: paid_at был, paid_by не было. Так что колонка закрывает дыру
-- разом в обоих местах.
--
-- ON DELETE SET NULL, а не CASCADE: увольнение тренера не должно стирать
-- историю платежей. Останется «кто-то отметил тогда-то» — это честнее, чем
-- потерять факт оплаты вместе с человеком.
--
-- Старые строки остаются с NULL: кто их отмечал, узнать неоткуда, и
-- придумывать автора задним числом нельзя.
--
-- НЕ ПРИМЕНЕНА. Прогонять вручную, см. команды в конце.

BEGIN;

ALTER TABLE athlete_fee_periods
    ADD COLUMN IF NOT EXISTS paid_by INTEGER
        REFERENCES users(id) ON DELETE SET NULL;

-- Источник отметки: 'cabinet' | 'bot'. Нужен, чтобы отличать привычный путь
-- от нового: если с ботом что-то пойдёт не так, выборка по нему покажет
-- масштаб сразу, без разбора логов.
ALTER TABLE athlete_fee_periods
    ADD COLUMN IF NOT EXISTS paid_source VARCHAR(20);

COMMIT;

