"""Экранирование данных, попадающих в размеченные сообщения.

Telegram и MAX оба разбирают текст сообщения как HTML (parse_mode="HTML" и
format="html" соответственно). Это значит, что любые данные из базы —
название соревнования, место, фамилия, заголовок новости — попадая в текст
без обработки, разбираются как разметка.

Чем это кончается:

  * «Кубок <Тайпан>» — Telegram видит неизвестный тег <Тайпан> и отвечает
    400 Bad Request: can't parse entities. Сообщение НЕ доходит целиком,
    причём об этом узнаёт только лог;
  * «Иванов & сыновья» — амперсанд без точки с запятой формально невалиден;
  * «Разряд <b>первый» — незакрытый тег утаскивает жирным весь остаток
    сообщения, включая соседние строки.

Ни один из случаев не выдумка: названия событий и новостей вводит человек
через админку, ограничений на символы там нет.

Функция намеренно живёт в core, а не в транспорте: правило одно на оба
мессенджера, и дублировать его — значит однажды поправить только в одном.
"""


def esc(value) -> str:
    """Экранировать значение для вставки в HTML-размеченное сообщение.

    Порядок замен важен: амперсанд первым, иначе он испортит уже
    подставленные &lt; и &gt;.

    Применять к КАЖДОЙ подстановке данных. Теги разметки пишутся вокруг
    результата, а не внутри него:

        f"<b>{esc(event.title)}</b>"        — верно
        esc(f"<b>{event.title}</b>")        — неверно, съест и разметку
    """
    return (str(value if value is not None else "")
            .replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;"))
