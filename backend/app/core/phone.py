"""Единая нормализация телефона.

Фронтенд отправляет телефон как чистые цифры с ведущей семёркой (79091652800),
но часть аккаунтов заведена вручную через SQL в других форматах: с «+», с
ведущей «8», без кода страны. Такие пользователи не могут войти — поиск по
User.phone не находит запись, и /login честно отдаёт 401 «Неверный телефон или
пароль» при верном пароле.

Логика намеренно повторяет frontend/src/utils/phone.js → normalizePhone(),
чтобы обе стороны приводили номер к одному и тому же виду.
"""

import re


def normalize_phone(value: str) -> str:
    """Приводит телефон к каноничному виду: только цифры, ведущая 8 → 7, без «+».

    '+7 (909) 165-28-00' → '79091652800'
    '89091652800'        → '79091652800'
    '9091652800'         → '79091652800'
    """
    if value is None:
        return ""
    digits = re.sub(r"\D", "", value)
    if not digits:
        return ""
    if digits.startswith("8"):
        return "7" + digits[1:]
    if digits.startswith("7"):
        return digits
    return "7" + digits
