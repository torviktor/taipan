#!/bin/sh
# Суточные дампы БД и ротация каталога бэкапов.
#
# Раньше это был однострочник в docker-compose.yml:
#     pg_dump $DATABASE_URL > /backups/backup_$(date ...).sql; sleep 86400
# У него две беды, обе подтверждены фактами на 22.08.2026.
#
# 1. Перенаправление создаёт файл ДО запуска pg_dump, поэтому упавший
#    pg_dump оставлял дамп нулевого размера — и выглядел как успешный.
#    Таких файлов нашлось 2 из 50, то есть 4% суток были без резервной
#    копии, и об этом никто не знал. Теперь дамп пишется во временный
#    файл и переименовывается только после успешного выхода pg_dump.
# 2. umask по умолчанию давал файлам права 644. Каталог 700 закрывает
#    их от чужих глаз, но внутри дампа — ФИО детей, телефоны родителей
#    и суммы взносов, так что права ставим явно.
#
# ─── Два срока хранения, и они разные намеренно ──────────────────────────────
#
# auto/   — суточные дампы, 30 дней. Их много, они однотипны, ценность
#           каждого отдельного невелика.
# manual/ — копии, снятые руками перед необратимыми операциями (миграции,
#           массовые правки). Держим 180 дней: там персональные данные детей,
#           и бессрочное хранение избыточно, но копия должна пережить период,
#           за который изменение успевает доказать работоспособность.
#
# Ротация auto/ выполняется только после УСПЕШНОГО дампа — иначе неудачная
# ночь стоила бы разом и свежей копии, и месячного архива. Ротация manual/
# от результата дампа не зависит: там сроки длинные и спешки нет.

set -u

ROOT=/backups
AUTO="$ROOT/auto"
MANUAL="$ROOT/manual"
KEEP_AUTO=30
KEEP_MANUAL=180

umask 077

log() { echo "[db-backup] $(date -u +%Y-%m-%dT%H:%M:%SZ) $*"; }

mkdir -p "$AUTO" "$MANUAL"

while true; do
    STAMP=$(date +%Y%m%d_%H%M%S)
    TMP="$AUTO/.tmp_$STAMP.sql"
    DST="$AUTO/backup_$STAMP.sql"

    if pg_dump "$DATABASE_URL" > "$TMP" 2>/tmp/pg_dump.err; then
        # Пустой файл при нулевом коде возврата — теоретически невозможен,
        # но именно такие «невозможные» случаи мы и ловим постфактум.
        if [ -s "$TMP" ]; then
            mv "$TMP" "$DST"
            log "дамп готов: $(basename "$DST"), $(wc -c < "$DST") байт"

            DELETED=$(find "$AUTO" -maxdepth 1 -name 'backup_*.sql' \
                          -mtime +$KEEP_AUTO -print -delete | wc -l)
            [ "$DELETED" -gt 0 ] && log "ротация auto: удалено $DELETED старше $KEEP_AUTO дней"
        else
            log "ОШИБКА: pg_dump вернул 0, но файл пуст — дамп отброшен"
            rm -f "$TMP"
        fi
    else
        log "ОШИБКА: pg_dump упал: $(head -c 200 /tmp/pg_dump.err)"
        rm -f "$TMP"
    fi

    # Ручные копии живут дольше и чистятся независимо от исхода дампа.
    DELETED_M=$(find "$MANUAL" -maxdepth 1 -type f \
                    -mtime +$KEEP_MANUAL -print -delete | wc -l)
    [ "$DELETED_M" -gt 0 ] && log "ротация manual: удалено $DELETED_M старше $KEEP_MANUAL дней"

    # Подчистка временных файлов, осиротевших при убийстве контейнера
    # посреди дампа: без этого они копились бы вечно, никем не читаемые.
    find "$AUTO" -maxdepth 1 -name '.tmp_*.sql' -mmin +180 -delete

    sleep 86400
done
